"""
End-to-end smoke/integration tests for PRAMIGO, run against the tiny synthetic
dataset generated by simulate_data.py (3 groups x 3 patients, 2 omics x 20
features, 10 differentially-expressed features per omic).

Starts from environment creation: the test suite provisions its own fresh venv
using the exact commands documented in README.md (`uv venv --python 3.8` +
`uv pip install -r env/biomixhgt_env.txt`), then runs every subsequent stage -
loading, training (+ resume), saving outputs, and visualization - through THAT
interpreter, for both a 2-group and a 3-group condition setup. This validates
the documented setup instructions themselves, not just the code assuming
dependencies are already present. Both group scenarios reuse the exact same
simulated omic matrices; only the metadata's CONDITION labels differ (the
2-group version merges GroupB and GroupC), so a single
`python src/simulate_data.py` run covers both.

Run manually with:
    pytest src/test_biomix_pipeline.py -v -s

This is a slow integration test - provisioning the environment plus both
pipeline runs takes a few minutes even on this toy-sized data - not something
to run in a tight edit/test loop. Requires the simulated data to exist first:
`python src/simulate_data.py`. Requires `uv` on PATH; environment-setup tests
skip (rather than fail) if it isn't available.
"""
import os
import sys
import shutil
import subprocess

import pandas as pd
import numpy as np
import pytest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(REPO_ROOT, "src")
SIM_DATA_DIR = os.path.join(REPO_ROOT, "data", "simulated_toy")
BIOMIX_SCRIPT = os.path.join(SRC_DIR, "biomix_hgt.py")
ENV_REQUIREMENTS = os.path.join(REPO_ROOT, "env", "biomixhgt_env.txt")

METADATA_3GROUP = os.path.join(SIM_DATA_DIR, "simulated_metadata.tsv")
OMIC1_PATH = os.path.join(SIM_DATA_DIR, "simulated_omic1.tsv")
OMIC2_PATH = os.path.join(SIM_DATA_DIR, "simulated_omic2.tsv")
GROUND_TRUTH_PATH = os.path.join(SIM_DATA_DIR, "simulated_ground_truth.tsv")

N_SAMPLES = 9
N_FEATURES_PER_OMIC = 20
N_DE_PER_OMIC = 10

# Hyperparameters tuned for a 9-sample, 20-feature-per-omic toy dataset. The script's
# defaults (--n_batch 25, --omic*_corr_cutoff 0.7) would either divide the per-batch
# feature counts down to zero (gene_num/metabo_num = int(20/25) = 0) or leave the tiny
# correlation-based graph nearly disconnected - both would break the run outright.
FAST_HPARAMS = [
    "--epoch", "4",
    "--n_batch", "2",
    "--n_hid", "8",
    "--ae_n_hid", "8",
    "--n_heads", "2",
    "--n_layers", "2",
    "--omic1_corr_cutoff", "0.3",
    "--omic2_corr_cutoff", "0.3",
    "--leiden_min_cluster_size", "2",
    "--cuda", "1",
    "--checkpoint_every", "1",
]


def make_two_group_metadata(out_path):
    """Derives a 2-condition metadata file from the 3-group simulated metadata by
    merging GroupB and GroupC into one label. Reuses the exact same omic matrices as
    the 3-group scenario, so only the grouping structure changes between the two."""
    metadata = pd.read_csv(METADATA_3GROUP, sep="\t")
    metadata["CONDITION"] = metadata["CONDITION"].replace({"GroupC": "GroupB"})
    metadata.to_csv(out_path, sep="\t", index=False)
    return str(out_path)


def run_biomix(python_executable, metadata_path, result_dir, extra_args=None):
    """Runs the real biomix_hgt.py script as a subprocess (it's a flat script with
    no importable functions/main guard, so subprocess is the only way to exercise it
    end-to-end), through the given interpreter - normally the one provisioned by
    `provisioned_python` below, not whatever interpreter happens to be running pytest.
    `extra_args` are appended after FAST_HPARAMS, so passing e.g. ["--epoch", "2"]
    overrides FAST_HPARAMS's --epoch via argparse's last-value-wins."""
    cmd = [
        str(python_executable), BIOMIX_SCRIPT,
        "--metadata_path", str(metadata_path),
        "--omic1_path", OMIC1_PATH,
        "--omic2_path", OMIC2_PATH,
        "--result_dir", str(result_dir),
    ] + FAST_HPARAMS + (extra_args or [])
    return subprocess.run(cmd, cwd=SRC_DIR, capture_output=True, text=True, timeout=900)


def _assert_success(proc):
    assert proc.returncode == 0, (
        f"biomix_hgt.py exited with code {proc.returncode}.\n"
        f"--- stdout (tail) ---\n{proc.stdout[-3000:]}\n"
        f"--- stderr (tail) ---\n{proc.stderr[-3000:]}"
    )


# ---------------------------------------------------------------------------
# Environment provisioning: create the venv exactly as README.md documents, and
# hand its interpreter to every other fixture/test in this file. Session-scoped
# so it's provisioned once and reused, not once per test.
# ---------------------------------------------------------------------------
@pytest.fixture(scope="session")
def provisioned_python(tmp_path_factory):
    uv = shutil.which("uv")
    if uv is None:
        pytest.skip("`uv` is not on PATH; cannot provision the environment as documented in README.md")

    venv_dir = tmp_path_factory.mktemp("hgt_env")
    create_proc = subprocess.run(
        [uv, "venv", str(venv_dir), "--python", "3.8"],
        capture_output=True, text=True, timeout=300
    )
    assert create_proc.returncode == 0, (
        f"`uv venv --python 3.8` failed.\nstdout: {create_proc.stdout}\nstderr: {create_proc.stderr}"
    )

    python_exe = venv_dir / ("Scripts" if os.name == "nt" else "bin") / ("python.exe" if os.name == "nt" else "python")
    assert python_exe.exists(), f"Expected a venv interpreter at {python_exe} after `uv venv`"

    install_proc = subprocess.run(
        [uv, "pip", "install", "--python", str(python_exe), "-r", ENV_REQUIREMENTS],
        capture_output=True, text=True, timeout=900
    )
    assert install_proc.returncode == 0, (
        f"`uv pip install -r env/biomixhgt_env.txt` failed.\n"
        f"stdout: {install_proc.stdout[-3000:]}\nstderr: {install_proc.stderr[-3000:]}"
    )
    return str(python_exe)


class TestEnvironmentSetup:
    """Validates the README's documented setup steps actually work, independent of
    anything pipeline-specific - if these fail, the problem is the environment/
    dependency pins, not biomix_hgt.py's logic."""

    def test_uv_is_available(self):
        assert shutil.which("uv") is not None, "uv is required to follow the README's documented setup instructions"

    def test_venv_creation_and_dependency_install_succeeds(self, provisioned_python):
        assert os.path.exists(provisioned_python)

    def test_key_dependencies_importable_in_provisioned_env(self, provisioned_python):
        check = subprocess.run(
            [provisioned_python, "-c",
             "import torch, torch_geometric, igraph, leidenalg, umap, plotly, "
             "pandas, numpy, sklearn, networkx, matplotlib, seaborn; print('IMPORT_OK')"],
            capture_output=True, text=True, timeout=120
        )
        assert check.returncode == 0 and "IMPORT_OK" in check.stdout, (
            f"stdout: {check.stdout}\nstderr: {check.stderr}"
        )


