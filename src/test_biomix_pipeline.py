# Parametrized end-to-end checks, run once each for the 2-group and 3-group scenario.
# ---------------------------------------------------------------------------
@pytest.mark.parametrize("run_fixture_name", ["two_group_run", "three_group_run"])
class TestPipelineEndToEnd:

    def test_process_completes_successfully(self, request, run_fixture_name):
        proc, _ = request.getfixturevalue(run_fixture_name)
        _assert_success(proc)

    def test_training_checkpoint_and_loss_history_saved(self, request, run_fixture_name):
        _, result_dir = request.getfixturevalue(run_fixture_name)
        checkpoint_path = os.path.join(result_dir, "model", "checkpoint_latest.pt")
        assert os.path.exists(checkpoint_path), "Training checkpoint was not saved"

        loss_dir = os.path.join(result_dir, "loss")
        loss_files = os.listdir(loss_dir)
        assert any("total_losses" in f for f in loss_files), "Total loss history CSV missing"
        assert any("val_losses" in f for f in loss_files), "Validation loss history CSV missing"

        total_losses = pd.read_csv(os.path.join(loss_dir, [f for f in loss_files if "total_losses" in f][0]))
        assert len(total_losses) == 4  # matches FAST_HPARAMS --epoch 4

    def test_embeddings_saved_with_expected_shapes(self, request, run_fixture_name):
        # Per-omic output dirs are named after each omic's manifest `name` (see
        # omics_manifest.py / biomix_hgt.py's `omic_dirs`), not hardcoded "gene"/
        # "metabo" - run_biomix() uses the legacy --omic1_path/--omic2_path flags,
        # which manifest_from_legacy_args() wraps into a 2-entry manifest named
        # "omic1"/"omic2", so those are the directories a run actually creates.
        _, result_dir = request.getfixturevalue(run_fixture_name)
        omic1_files = os.listdir(os.path.join(result_dir, "omic1"))
        omic2_files = os.listdir(os.path.join(result_dir, "omic2"))
        sample_files = os.listdir(os.path.join(result_dir, "sample"))
        assert len(omic1_files) == 1 and len(omic2_files) == 1 and len(sample_files) == 1

        omic1_matrix = pd.read_csv(os.path.join(result_dir, "omic1", omic1_files[0]), sep=" ", header=None)
        assert omic1_matrix.shape[0] == N_FEATURES_PER_OMIC
        omic2_matrix = pd.read_csv(os.path.join(result_dir, "omic2", omic2_files[0]), sep=" ", header=None)
        assert omic2_matrix.shape[0] == N_FEATURES_PER_OMIC
        sample_matrix = pd.read_csv(os.path.join(result_dir, "sample", sample_files[0]), sep=" ", header=None)
        assert sample_matrix.shape[0] == N_SAMPLES

    def test_attention_csv_saved(self, request, run_fixture_name):
        _, result_dir = request.getfixturevalue(run_fixture_name)
        att_files = [f for f in os.listdir(os.path.join(result_dir, "att")) if f.endswith(".csv")]
        assert len(att_files) == 1
        att_df = pd.read_csv(os.path.join(result_dir, "att", att_files[0]))
        assert att_df.shape[0] > 0, "Attention edge table is empty"

    def test_core_visualizations_saved(self, request, run_fixture_name):
        _, result_dir = request.getfixturevalue(run_fixture_name)
        plots_dir = os.path.join(result_dir, "plots")
        expected_always = [
            "training_loss_components.pdf",
            "Confusion_matrix_figure.pdf",
            "Interpretability_nodes_attention_figure.pdf",
            "embeddings_evaluations_figure.pdf",
            "network_interactive.html",
        ]
        for filename in expected_always:
            assert os.path.exists(os.path.join(plots_dir, filename)), f"Missing expected output: {filename}"

    def test_leiden_cluster_outputs_if_any_cluster_formed(self, request, run_fixture_name):
        """With only 40 total candidate features, whether Leiden finds any cluster
        >= --leiden_min_cluster_size is data/seed-dependent (topology of a tiny
        correlation graph). This check is intentionally tolerant: if the pipeline
        itself reported no valid clusters, it skips rather than failing."""
        proc, result_dir = request.getfixturevalue(run_fixture_name)
        if ("no clusters passed the minimum size filter" in proc.stdout
                or "no connected top-feature subgraph found" in proc.stdout):
            pytest.skip("No Leiden clusters formed for this toy dataset/seed - nothing to check.")
        plots_dir = os.path.join(result_dir, "plots")
        for filename in [
            "leiden_clusters_composition.csv",
            "leiden_cluster_network.pdf",
            "leiden_cluster_subgraphs.pdf",
            "leiden_program_activity_scores.csv",
            "leiden_program_activity_report.pdf",
        ]:
            assert os.path.exists(os.path.join(plots_dir, filename)), f"Missing expected output: {filename}"

    def test_supplementary_visualizations_saved(self, request, run_fixture_name):
        _, result_dir = request.getfixturevalue(run_fixture_name)
        supplementary_dir = os.path.join(result_dir, "supplementary")
        expected = [
            "loss_lr_schedule.pdf", "loss_component_share.pdf",
            "roc_curves.pdf", "per_class_performance.pdf",
            "attention_concentration_by_omic.pdf", "attention_distribution_by_omic.pdf",
            "embedding_separability_silhouette.pdf", "embedding_pca_scree.pdf",
            "network_hub_nodes.pdf",
        ]
        for filename in expected:
            assert os.path.exists(os.path.join(supplementary_dir, filename)), f"Missing supplementary output: {filename}"


# ---------------------------------------------------------------------------
# Resume/checkpoint feature: train partially, resume, and confirm training
# actually continued from the checkpoint rather than restarting from epoch 0.
# ---------------------------------------------------------------------------
class TestResumeTraining:

    def test_resume_continues_past_the_checkpointed_epoch(self, provisioned_python, tmp_path):
        result_dir = tmp_path / "resume_result"

        first_pass = run_biomix(provisioned_python, METADATA_3GROUP, result_dir, extra_args=["--epoch", "2"])
        _assert_success(first_pass)
        loss_dir = os.path.join(result_dir, "loss")
        first_file = [f for f in os.listdir(loss_dir) if "total_losses" in f][0]
        assert len(pd.read_csv(os.path.join(loss_dir, first_file))) == 2

        second_pass = run_biomix(provisioned_python, METADATA_3GROUP, result_dir, extra_args=["--epoch", "4", "--resume"])
        _assert_success(second_pass)
        assert "Resuming HGT training from checkpoint" in second_pass.stdout
        assert "Resumed at epoch 2" in second_pass.stdout

        second_file = [f for f in os.listdir(loss_dir) if "total_losses" in f][0]
        second_losses = pd.read_csv(os.path.join(loss_dir, second_file))
        assert len(second_losses) == 4, "Resumed run should carry the full 4-epoch loss history, not just the resumed 2"

    def test_resume_flag_without_existing_checkpoint_falls_back_to_fresh_training(self, provisioned_python, tmp_path):
        result_dir = tmp_path / "resume_no_checkpoint_result"
        proc = run_biomix(provisioned_python, METADATA_3GROUP, result_dir, extra_args=["--epoch", "2", "--resume"])
        _assert_success(proc)
        assert "no checkpoint was found" in proc.stdout

    def test_resume_past_completed_training_exits_cleanly(self, provisioned_python, tmp_path):
        """Resuming with --epoch <= the checkpoint's completed epoch has nothing to
        do (the rest of the script depends on the training loop having executed at
        least once) - it should exit(0) with a clear message, not crash later on
        with a confusing NameError."""
        result_dir = tmp_path / "resume_already_done_result"
        first_pass = run_biomix(provisioned_python, METADATA_3GROUP, result_dir, extra_args=["--epoch", "2"])
        _assert_success(first_pass)

        second_pass = run_biomix(provisioned_python, METADATA_3GROUP, result_dir, extra_args=["--epoch", "2", "--resume"])
        assert second_pass.returncode == 0
        assert "Nothing to resume" in second_pass.stdout


