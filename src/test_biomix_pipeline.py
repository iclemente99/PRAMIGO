# ---------------------------------------------------------------------------
# 0. Loading: validate the simulated inputs themselves, independent of the
#    pipeline, so a failure here points at the data rather than at the model.
# ---------------------------------------------------------------------------
class TestSimulatedDataLoading:

    def test_simulated_files_exist(self):
        for path in [METADATA_3GROUP, OMIC1_PATH, OMIC2_PATH, GROUND_TRUTH_PATH]:
            assert os.path.exists(path), f"Missing simulated input: {path}. Run `python src/simulate_data.py` first."

    def test_metadata_has_required_columns_and_three_groups(self):
        metadata = pd.read_csv(METADATA_3GROUP, sep="\t")
        assert {"ID", "CONDITION"}.issubset(metadata.columns)
        assert len(metadata) == N_SAMPLES
        assert metadata["CONDITION"].nunique() == 3
        assert (metadata["CONDITION"].value_counts() == 3).all()

    def test_two_group_metadata_derivation_merges_to_two_conditions(self, tmp_path):
        two_group_path = make_two_group_metadata(tmp_path / "meta2.tsv")
        metadata = pd.read_csv(two_group_path, sep="\t")
        assert len(metadata) == N_SAMPLES  # same samples, just relabeled
        assert metadata["CONDITION"].nunique() == 2

    def test_omic_matrices_align_with_metadata_and_have_expected_shape(self):
        metadata = pd.read_csv(METADATA_3GROUP, sep="\t")
        for path in [OMIC1_PATH, OMIC2_PATH]:
            omic_df = pd.read_csv(path, sep="\t")
            assert omic_df.columns[0] == "ID"
            assert set(omic_df.columns[1:]) == set(metadata["ID"])
            assert omic_df.shape[0] == N_FEATURES_PER_OMIC

    def test_omic_matrices_are_row_normalized(self):
        """Each feature (row) should be ~zero-mean, unit-variance across samples,
        since biomix_hgt.py expects pre-normalized input and does no normalization
        of its own."""
        for path in [OMIC1_PATH, OMIC2_PATH]:
            omic_df = pd.read_csv(path, sep="\t")
            values = omic_df.iloc[:, 1:].values
            #assert (values.mean(axis=1) == pytest.approx(0, abs=1e-6)).all()
            #assert (values.std(axis=1) == pytest.approx(1, abs=1e-6)).all()
            assert np.allclose(values.mean(axis=1), 0, atol=1e-6)
            assert np.allclose(values.std(axis=1), 1, atol=1e-6)

    def test_ground_truth_marks_exactly_ten_de_features_per_omic(self):
        ground_truth = pd.read_csv(GROUND_TRUTH_PATH, sep="\t")
        for omic in ["omic1", "omic2"]:
            de_count = ground_truth[
                (ground_truth["Omic"] == omic) & (ground_truth["Is_Differentially_Expressed"])
            ].shape[0]
            assert de_count == N_DE_PER_OMIC


